        public static bool TryGetPattern(char c, out string[] rows)
        {
            var key = char.ToUpperInvariant(c);
            if (Patterns.TryGetValue(key, out var pattern))
            {
                rows = pattern;
                return true;
            }

            rows = Array.Empty<string>();
            return false;
        }

        public static bool[] GetMatrixBits(char c)
        {
            if (!TryGetPattern(c, out var rows))
            {
                return new bool[Width * Height];
            }

            var bits = new bool[Width * Height];
            for (int row = 0; row < Height; row++)
            {
                for (int col = 0; col < Width; col++)
                {
                    bits[(row * Width) + col] = rows[row][col] == '1';
                }
            }

            return bits;
        }
